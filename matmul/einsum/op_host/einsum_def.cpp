/*!
 * \file einsum_def.cpp
 * \brief 算子信息库定义：Einsum（动态输入x/输出y + equation/N必选属性），图模式由einsum_fusion_pass分解
 */

#include "register/op_def_registry.h"

namespace ops {
class Einsum : public OpDef {
public:
    explicit Einsum(const char* name) : OpDef(name)
    {
        this->Input("x")
            .ParamType(DYNAMIC)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT, ge::DT_INT32})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND});
        this->Output("y")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT, ge::DT_INT32})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND});
        this->Attr("equation").AttrType(REQUIRED).String("");
        this->Attr("N").AttrType(REQUIRED).Int(0);

        OpAICoreConfig aicore_config;
        aicore_config.DynamicShapeSupportFlag(true);
        this->AICore().AddConfig("ascend310p", aicore_config);
        this->AICore().AddConfig("ascend910b", aicore_config);
        this->AICore().AddConfig("ascend910_93", aicore_config);
        this->AICore().AddConfig("ascend950", aicore_config);
    }
};

OP_ADD(Einsum);
} // namespace ops
