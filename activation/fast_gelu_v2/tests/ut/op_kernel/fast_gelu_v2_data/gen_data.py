import os
import sys

import numpy as np

os.environ.setdefault("TORCH_DEVICE_BACKEND_AUTOLOAD", "0")

import torch


def fast_gelu_v2_torch(x):
    eps = 1.0e-12
    x_eps = x + eps
    sgn_x = torch.clamp(x_eps / torch.abs(x_eps), min=-1.0, max=1.0)
    clipped = torch.clamp(0.7071 * torch.abs(x), max=1.769)
    inner = -0.1444 * (clipped - 1.769) ** 2 + 0.5
    return x * (sgn_x * inner + 0.5)


def gen_golden_data_simple(shape_str, dtype):
    shape_list = [int(s) for s in shape_str.strip("(").strip(")").split(",")]
    shape = tuple(shape_list)
    dtype_dict = {
        "float32": torch.float32,
        "float16": torch.float16,
        "bfloat16": torch.bfloat16,
    }
    if dtype not in dtype_dict:
        raise ValueError("unsupported dtype: %s" % dtype)

    data_fp32 = torch.from_numpy(np.random.uniform(-5, 5, shape).astype(np.float32))
    data_x = data_fp32.to(dtype_dict[dtype])
    x_compute = data_x.to(torch.float32)
    golden = fast_gelu_v2_torch(x_compute).to(dtype_dict[dtype])

    if dtype == "bfloat16":
        data_x.view(torch.int16).numpy().tofile("./input_x.bin")
        golden.view(torch.int16).numpy().tofile("./golden.bin")
    else:
        data_x.numpy().tofile("./input_x.bin")
        golden.numpy().tofile("./golden.bin")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print("Usage: python gen_data.py <shape> <dtype>")
        print("Example: python gen_data.py '(256)' float32")
        exit(1)
    gen_golden_data_simple(sys.argv[1], sys.argv[2])
