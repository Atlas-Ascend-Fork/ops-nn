    coreNum = std::min(coreNum, availableCoreNum);

    int64_t blockFormer = CeilAlign(CeilDiv(dim0, coreNum), ELEM_ALIGN_FACTOR);
    int64_t blockNum = CeilDiv(dim0, blockFormer);

