static gert::StorageShape MakeStorageShape(const std::vector<int64_t>& dims)
{
    gert::StorageShape shape;
    for (auto dim : dims) {
        shape.MutableOriginShape().AppendDim(dim);
        shape.MutableStorageShape().AppendDim(dim);
    }
    return shape;
}

static std::vector<int64_t> ShapeToVec(const gert::Shape* s)
{
    std::vector<int64_t> v;
    if (s == nullptr)
        return v;
    for (size_t i = 0; i < s->GetDimNum(); ++i) {
        v.push_back(s->GetDim(i));
    }
    return v;
}

static ge::graphStatus RunAndGetOutputShape(gert::StorageShape& tensorShape, gert::StorageShape& scalarShape,
                                            std::vector<int64_t>& outputDims)
{
    auto* opImpl = gert::OpImplRegistry::GetInstance().GetOpImpl("InplaceApplyRMSProp");
    if (opImpl == nullptr) {
        return ge::GRAPH_FAILED;
    }
    auto inferShapeFunc = opImpl->infer_shape;
    if (inferShapeFunc == nullptr) {
        return ge::GRAPH_FAILED;
    }

    gert::StorageShape outputShape = {{}, {}};
    auto holder = gert::InferShapeContextFaker()
                      .NodeIoNum(8, 3)
                      .IrInstanceNum({1, 1, 1, 1, 1, 1, 1, 1})
                      .InputShapes({&tensorShape, &tensorShape, &tensorShape, &scalarShape, &scalarShape, &scalarShape,
                                    &scalarShape, &tensorShape})
                      .OutputShapes({&outputShape, &outputShape, &outputShape})
                      .Build();

    auto* ctx = holder.GetContext<gert::InferShapeContext>();
    auto status = inferShapeFunc(ctx);
    if (status == ge::GRAPH_SUCCESS) {
        outputDims = ShapeToVec(ctx->GetOutputShape(0));
    }
    return status;
}

