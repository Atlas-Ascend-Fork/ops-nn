static ge::graphStatus ComputeSplit(gert::TilingContext* context, InplaceApplyRmsPropTilingData* tiling,
                                    ge::DataType dataType, uint64_t ubSize, int64_t coreNum, int64_t ubBlockSizeBytes,
                                    uint64_t& bufferMode, int64_t& usedCoreNum)
{
    if (ubBlockSizeBytes <= 0) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "ubBlockSizeBytes",
                                              std::to_string(ubBlockSizeBytes), "UB block size must be greater than 0");
        return ge::GRAPH_FAILED;
    }
    const int64_t dataTypeBytes = GetDataTypeBytes(dataType);
    const int64_t alignElements = ubBlockSizeBytes / dataTypeBytes;
    if (alignElements <= 0) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "alignElements", std::to_string(alignElements),
                                              "UB element alignment must be greater than 0");
        return ge::GRAPH_FAILED;
    }

    tiling->blockFactor = CeilAlign(CeilDiv(tiling->totalNum, coreNum), alignElements);
    bufferMode = tiling->totalNum > MIN_SPLIT_THRESHOLD ? DOUBLE_BUFFER_MODE : SINGLE_BUFFER_MODE;

    const int64_t scalarReserveBytes = GetScalarUbReserveBytes(dataType);
    const int64_t usableUbBytes = static_cast<int64_t>(ubSize);
    if (ubSize <= static_cast<uint64_t>(scalarReserveBytes)) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "ubSize", std::to_string(ubSize),
                                              "UB size is insufficient for scalar input buffer");
        return ge::GRAPH_FAILED;
    }
    const int64_t tensorUbBytes = usableUbBytes - scalarReserveBytes;
    const int64_t tensorBytesPerElement = GetTensorBytesPerElement(dataType, bufferMode);
    if (tensorBytesPerElement <= 0) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "tensorBytesPerElement",
                                              std::to_string(tensorBytesPerElement),
                                              "tensor UB byte cost must be greater than 0");
        return ge::GRAPH_FAILED;
    }
    const int64_t maxUbElements = FloorDiv(tensorUbBytes, tensorBytesPerElement);
    // Only the reduced-precision paths load UB into vector registers with full-width, unmasked
    // Reg::DataCopy, so only they need ubFactor to be a multiple of the platform's fp32 vector
    // lane count; the fp32 path keeps the native UB block alignment.
    int64_t ubAlignment = alignElements;
    if (dataType != ge::DT_FLOAT) {
        const int64_t vfLaneElements = GetVfLaneElements(context);
        ubAlignment = vfLaneElements > ubAlignment ? vfLaneElements : ubAlignment;
    }
    tiling->ubFactor = FloorAlign(maxUbElements, ubAlignment);
    if (tiling->ubFactor <= 0) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "ubFactor", std::to_string(tiling->ubFactor),
                                              "ubFactor must be greater than 0");
        return ge::GRAPH_FAILED;
    }

    usedCoreNum = CeilDiv(tiling->totalNum, tiling->blockFactor);
    if (usedCoreNum <= 0) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "usedCoreNum", std::to_string(usedCoreNum),
                                              "usedCoreNum must be greater than 0");
        return ge::GRAPH_FAILED;
    }
    return ge::GRAPH_SUCCESS;
}

