static ge::graphStatus InplaceApplyRMSPropTilingFunc(gert::TilingContext* context)
{
    OP_LOGI(context->GetNodeName(), "Enter InplaceApplyRMSPropTilingFunc");
    uint64_t ubSize = 0;
    int64_t coreNum = 0;
    if (GetPlatformInfo(context, ubSize, coreNum) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    int64_t totalNum = 0;
    ge::DataType dataType = ge::DT_FLOAT;
    if (GetShapeAndDataType(context, totalNum, dataType) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    if (SetWorkspace(context) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    InplaceApplyRmsPropTilingData* tiling = nullptr;
    if (InitTilingData(context, totalNum, tiling) != ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    uint32_t schMode = DataTypeToSchMode(dataType);
    if (totalNum == 0) {
        return HandleEmptyTensor(context, schMode);
    }

    uint64_t bufferMode = SINGLE_BUFFER_MODE;
    int64_t usedCoreNum = 0;
    if (ComputeSplit(context, tiling, dataType, ubSize, coreNum, GetUbBlockSize(context), bufferMode, usedCoreNum) !=
        ge::GRAPH_SUCCESS) {
        return ge::GRAPH_FAILED;
    }

    context->SetBlockDim(usedCoreNum);
    ASCENDC_TPL_SEL_PARAM(context, schMode, static_cast<uint32_t>(bufferMode));
    return ge::GRAPH_SUCCESS;
}

