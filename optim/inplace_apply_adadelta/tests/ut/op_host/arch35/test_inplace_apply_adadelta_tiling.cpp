static InplaceApplyAdadeltaTilingResult DoInplaceApplyAdadeltaTilingCase(
    const std::initializer_list<int64_t>& varShape, const std::initializer_list<int64_t>& accumShape,
    const std::initializer_list<int64_t>& accumUpdateShape, const std::initializer_list<int64_t>& lrShape,
    const std::initializer_list<int64_t>& rhoShape, const std::initializer_list<int64_t>& epsilonShape,
    const std::initializer_list<int64_t>& gradShape, ge::DataType tensorDtype, ge::Format inputFormat, bool useLocking,
    bool normalizeVarRankZeroStorage = false, const std::array<ge::DataType, 7>* inputDtypes = nullptr,
    const std::array<ge::Format, 7>* inputOriginFormats = nullptr,
    const std::array<ge::Format, 7>* inputStorageFormats = nullptr)
{
    InplaceApplyAdadeltaTilingResult result{ge::GRAPH_FAILED, 0, 0, 0};

    // init ops-registry-invoke
    fe::PlatFormInfos platFormInfo;
    map<string, string> socInfos;
    map<string, string> aicoreSpec;
    map<string, string> intrinsics;
    map<string, string> socVersion = {{"Short_SoC_version", "ASCEND950"}};
    InitPlatForm(platFormInfo, socInfos, aicoreSpec, intrinsics, socVersion);

    std::string opType("InplaceApplyAdadelta");
    EXPECT_NE(gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str()), nullptr);
    if (gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str()) == nullptr) {
        return result;
    }

    auto tiling_func = gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str())->tiling;

    // tilingFunc simulate
    auto param = gert::TilingData::CreateCap(4096);
    auto workspace_size_holer = gert::ContinuousVector::Create<size_t>(4096);
    auto ws_size = reinterpret_cast<gert::ContinuousVector*>(workspace_size_holer.get());
    EXPECT_NE(param, nullptr);
    if (param == nullptr) {
        return result;
    }

    gert::StorageShape varStorage = {varShape, varShape};
    gert::StorageShape accumStorage = {accumShape, accumShape};
    gert::StorageShape accumUpdateStorage = {accumUpdateShape, accumUpdateShape};
    gert::StorageShape lrStorage = {lrShape, lrShape};
    gert::StorageShape rhoStorage = {rhoShape, rhoShape};
    gert::StorageShape epsilonStorage = {epsilonShape, epsilonShape};
    gert::StorageShape gradStorage = {gradShape, gradShape};
    if (normalizeVarRankZeroStorage) {
        varStorage.MutableStorageShape() = gert::Shape({1});
        accumStorage.MutableStorageShape() = gert::Shape({1});
        accumUpdateStorage.MutableStorageShape() = gert::Shape({1});
        gradStorage.MutableStorageShape() = gert::Shape({1});
    }
    // GE represents a logical rank-0 scalar with one physical storage element.
    if (lrShape.size() == 0) {
        lrStorage.MutableStorageShape() = gert::Shape({1});
    }
    if (rhoShape.size() == 0) {
        rhoStorage.MutableStorageShape() = gert::Shape({1});
    }
    if (epsilonShape.size() == 0) {
        epsilonStorage.MutableStorageShape() = gert::Shape({1});
    }

    InplaceApplyAdadeltaUtCompileInfo compileInfo;

    auto inputOriginFormat = [&](size_t index) {
        return inputOriginFormats == nullptr ? inputFormat : (*inputOriginFormats)[index];
    };
    auto inputStorageFormat = [&](size_t index) {
        return inputStorageFormats == nullptr ? inputFormat : (*inputStorageFormats)[index];
    };

    auto holder = gert::TilingContextFaker()
                      .SetOpType(opType)
                      .NodeIoNum(7, 3)
                      .IrInstanceNum({1, 1, 1, 1, 1, 1, 1})
                      .InputShapes({&varStorage, &accumStorage, &accumUpdateStorage, &lrStorage, &rhoStorage,
                                    &epsilonStorage, &gradStorage})
                      .OutputShapes({&varStorage, &accumStorage, &accumUpdateStorage})
                      .CompileInfo(&compileInfo)
                      .PlatformInfo(reinterpret_cast<char*>(&platFormInfo))
                      .NodeInputTd(0, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[0], inputOriginFormat(0),
                                   inputStorageFormat(0))
                      .NodeInputTd(1, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[1], inputOriginFormat(1),
                                   inputStorageFormat(1))
                      .NodeInputTd(2, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[2], inputOriginFormat(2),
                                   inputStorageFormat(2))
                      .NodeInputTd(3, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[3], inputOriginFormat(3),
                                   inputStorageFormat(3))
                      .NodeInputTd(4, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[4], inputOriginFormat(4),
                                   inputStorageFormat(4))
                      .NodeInputTd(5, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[5], inputOriginFormat(5),
                                   inputStorageFormat(5))
                      .NodeInputTd(6, inputDtypes == nullptr ? tensorDtype : (*inputDtypes)[6], inputOriginFormat(6),
                                   inputStorageFormat(6))
                      .NodeOutputTd(0, tensorDtype, inputFormat, inputFormat) // var
                      .NodeOutputTd(1, tensorDtype, inputFormat, inputFormat) // accum
                      .NodeOutputTd(2, tensorDtype, inputFormat, inputFormat) // accum_update
                      .NodeAttrs({{"use_locking", Ops::NN::AnyValue::CreateFrom<bool>(useLocking)}})
                      .TilingData(param.get())
                      .Workspace(ws_size)
                      .Build();

    gert::TilingContext* tiling_context = holder.GetContext<gert::TilingContext>();
    EXPECT_NE(tiling_context->GetPlatformInfo(), nullptr);
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetPlatformRes("SoCInfo", socInfos);
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetPlatformRes("AICoreSpec", aicoreSpec);
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetCoreNumByCoreType("AICore");
    holder.GetContext<gert::TilingContext>()->GetPlatformInfo()->SetPlatformRes("AICoreintrinsicDtypeMap", intrinsics);
    tiling_context->GetPlatformInfo()->SetPlatformRes("version", socVersion);

    result.status = tiling_func(tiling_context);
    if (result.status == ge::GRAPH_SUCCESS) {
        result.tilingKey = tiling_context->GetTilingKey();
        // Parse TilingData struct. The empty Tensor path also initializes this
        // struct so the kernel can safely read totalNum and return immediately.
        auto rawTilingData = tiling_context->GetRawTilingData();
        if (rawTilingData != nullptr && rawTilingData->GetDataSize() >= sizeof(InplaceApplyAdadeltaTilingData)) {
            const auto* td = reinterpret_cast<const InplaceApplyAdadeltaTilingData*>(rawTilingData->GetData());
            result.useLocking = td->useLocking;
            result.totalNum = td->totalNum;
        }
    }
    return result;
}

