static void ResetErrMgr()
{
    (void)error_message::ErrMgrInit(error_message::ErrorMessageMode::INTERNAL_MODE);
    // INTERNAL_MODE records against a work stream; the default id 0 is invalid,
    // so bind a stable non-zero id before observing the tiling call.
    auto context = error_message::GetErrMgrContext();
    context.work_stream_id = 1U;
    error_message::SetErrMgrContext(context);
    (void)error_message::GetErrMgrRawErrorMessages();
}

static std::string ArgValue(const error_message::ErrMsgRawItem* item, const std::string& key)
{
    for (size_t i = 0; i < item->args_key.size() && i < item->args_value.size(); ++i) {
        if (item->args_key[i] != nullptr && key == item->args_key[i].get()) {
            return item->args_value[i] != nullptr ? item->args_value[i].get() : "";
        }
    }
    return "";
}

static ge::graphStatus DoCenteredTilingCase(std::initializer_list<int64_t> tensorShape,
                                            std::initializer_list<int64_t> lrShape, ge::DataType lrDtype)
{
    fe::PlatFormInfos platFormInfo;
    map<string, string> socInfos;
    map<string, string> aicoreSpec;
    map<string, string> intrinsics;
    map<string, string> socVersion = {{"Short_SoC_version", "ASCEND950"}};
    InitPlatForm(platFormInfo, socInfos, aicoreSpec, intrinsics, socVersion);

    std::string opType("InplaceApplyCenteredRMSProp");
    auto opImpl = gert::OpImplRegistry::GetInstance().GetOpImpl(opType.c_str());
    EXPECT_NE(opImpl, nullptr);
    if (opImpl == nullptr || opImpl->tiling == nullptr) {
        return ge::GRAPH_FAILED;
    }
    auto tiling_func = opImpl->tiling;

    auto param = gert::TilingData::CreateCap(4096);
    auto workspace_size_holer = gert::ContinuousVector::Create<size_t>(4096);
    auto ws_size = reinterpret_cast<gert::ContinuousVector*>(workspace_size_holer.get());
    EXPECT_NE(param, nullptr);
    if (param == nullptr) {
        return ge::GRAPH_FAILED;
    }

    gert::StorageShape varShape = {tensorShape, tensorShape};
    gert::StorageShape mgShape = {tensorShape, tensorShape};
    gert::StorageShape msShape = {tensorShape, tensorShape};
    gert::StorageShape momShape = {tensorShape, tensorShape};
    gert::StorageShape lrStorage = {lrShape, lrShape};
    gert::StorageShape rhoShape = {{1}, {1}};
    gert::StorageShape momentumShape = {{1}, {1}};
    gert::StorageShape epsilonShape = {{1}, {1}};
    gert::StorageShape gradShape = {tensorShape, tensorShape};

    InplaceApplyCenteredRMSPropUtCompileInfo compileInfo;

    auto holder = gert::TilingContextFaker()
                      .SetOpType(opType)
                      .NodeIoNum(9, 4)
                      .IrInstanceNum({1, 1, 1, 1, 1, 1, 1, 1, 1})
                      .InputShapes({&varShape, &mgShape, &msShape, &momShape, &lrStorage, &rhoShape, &momentumShape,
                                    &epsilonShape, &gradShape})
                      .OutputShapes({&varShape, &mgShape, &msShape, &momShape})
                      .CompileInfo(&compileInfo)
                      .PlatformInfo(reinterpret_cast<char*>(&platFormInfo))
                      .NodeInputTd(0, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(1, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(2, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(3, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(4, lrDtype, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(5, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(6, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(7, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeInputTd(8, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeOutputTd(0, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeOutputTd(1, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeOutputTd(2, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .NodeOutputTd(3, ge::DT_FLOAT, ge::FORMAT_ND, ge::FORMAT_ND)
                      .TilingData(param.get())
                      .Workspace(ws_size)
                      .Build();

    gert::TilingContext* tiling_context = holder.GetContext<gert::TilingContext>();
    EXPECT_NE(tiling_context->GetPlatformInfo(), nullptr);
    tiling_context->GetPlatformInfo()->SetPlatformRes("SoCInfo", socInfos);
    tiling_context->GetPlatformInfo()->SetPlatformRes("AICoreSpec", aicoreSpec);
    tiling_context->GetPlatformInfo()->SetCoreNumByCoreType("AICore");
    tiling_context->GetPlatformInfo()->SetPlatformRes("AICoreintrinsicDtypeMap", intrinsics);
    tiling_context->GetPlatformInfo()->SetPlatformRes("version", socVersion);

    return tiling_func(tiling_context);
}

// lr storage rank 2 is neither a scalar nor a 1-D singleton tensor -> EZ0012.
TEST_F(TestInplaceApplyCenteredRMSPropTiling, centered_scalar_rank_gt1_reports_ez0012)
{
    ResetErrMgr();
    const auto status = DoCenteredTilingCase({2048}, {1, 1}, ge::DT_FLOAT);
    const auto errors = error_message::GetErrMgrRawErrorMessages();
    EXPECT_EQ(status, ge::GRAPH_FAILED);
    ASSERT_EQ(errors.size(), 1U);
    ASSERT_NE(errors[0].error_id, nullptr);
    EXPECT_STREQ(errors[0].error_id.get(), "EZ0012");
    EXPECT_EQ(ArgValue(&errors[0], "param_name"), "lr");
    EXPECT_EQ(ArgValue(&errors[0], "incorrect_dim"), "2");
    EXPECT_NE(ArgValue(&errors[0], "reason").find("rank must be 0 (scalar) or 1"), std::string::npos);
}

// lr rank 1 with two elements -> EZ0015.
TEST_F(TestInplaceApplyCenteredRMSPropTiling, centered_scalar_size_ne1_reports_ez0015)
{
    ResetErrMgr();
    const auto status = DoCenteredTilingCase({2048}, {2}, ge::DT_FLOAT);
    const auto errors = error_message::GetErrMgrRawErrorMessages();
    EXPECT_EQ(status, ge::GRAPH_FAILED);
    ASSERT_EQ(errors.size(), 1U);
    ASSERT_NE(errors[0].error_id, nullptr);
    EXPECT_STREQ(errors[0].error_id.get(), "EZ0015");
    EXPECT_EQ(ArgValue(&errors[0], "param_name"), "lr");
    EXPECT_EQ(ArgValue(&errors[0], "incorrect_size"), "2");
    EXPECT_NE(ArgValue(&errors[0], "reason").find("must contain exactly 1 element"), std::string::npos);
}

// lr dtype differs from var dtype -> EZ0021 (parameter relationship).
TEST_F(TestInplaceApplyCenteredRMSPropTiling, centered_scalar_dtype_mismatch_reports_ez0021)
{
    ResetErrMgr();
    const auto status = DoCenteredTilingCase({2048}, {1}, ge::DT_FLOAT16);
    const auto errors = error_message::GetErrMgrRawErrorMessages();
    EXPECT_EQ(status, ge::GRAPH_FAILED);
    ASSERT_EQ(errors.size(), 1U);
    ASSERT_NE(errors[0].error_id, nullptr);
    EXPECT_STREQ(errors[0].error_id.get(), "EZ0021");
    EXPECT_EQ(ArgValue(&errors[0], "param_names"), "var, lr");
    EXPECT_NE(ArgValue(&errors[0], "incorrect_dtypes").find("FLOAT16"), std::string::npos);
    EXPECT_NE(ArgValue(&errors[0], "reason").find("must equal dtype of var"), std::string::npos);
}
