// 期望值参考实现：与 README 公式 / kernel 的 fp32 运算顺序逐步对应
// （negP=0.5 走 Sqrt 特例路径，与 kernel E1/E2 的特例分支一致）。
// NaN 语义与 TF 一致：linear_new=NaN 时 var_out 经比较-选择输出 0。
struct FtrlV2Ref {
    float varOut;
    float accumNew;
    float linearNew;
};

FtrlV2Ref FtrlV2StepRef(float w, float n, float z, float g, float lr, float l1, float l2, float l2s, float p)
{
    const float negP = -p;
    const float gradHat = g + (2.0f * l2s) * w;
    const float accumNew = n + g * g;
    const float powOld = (negP == 0.5f) ? std::sqrt(n) : std::pow(n, negP);
    const float powNew = (negP == 0.5f) ? std::sqrt(accumNew) : std::pow(accumNew, negP);
    const float sigma = (powNew - powOld) / lr;
    const float linearNew = (z + gradHat) - sigma * w;
    const float x = l1 * static_cast<float>((linearNew > 0.0f) - (linearNew < 0.0f)) - linearNew;
    const float y = powNew / lr + 2.0f * l2;
    const float varOut = (std::fabs(linearNew) > l1) ? (x / y) : 0.0f;
    return {varOut, accumNew, linearNew};
}

