static constexpr int64_t UNKNOWN_DIM_VALUE = -1; // 动态维
static constexpr int64_t UNKNOWN_RANK_DIM = -2;  // 未知 rank（新框架以 1 维 [-2] 表示）
static constexpr size_t UNKNOWN_RANK_DIM_NUM = 1;
