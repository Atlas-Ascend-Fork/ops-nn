TilingRunResult TilingRunner::Run(const std::vector<std::vector<ForeachTensorSpec>>& inputs,
                                  const std::vector<ForeachTensorSpec>& outputs)
{
    TilingRunResult result;
    auto opImpl = gert::OpImplRegistry::GetInstance().GetOpImpl(kOpType);
    if (opImpl == nullptr || opImpl->tiling == nullptr) {
        return result;
    }

    // 输出只有一个 IR 原型（y），实例个数与传入的输出张量个数一致
    std::vector<uint32_t> outInstanceNum = {static_cast<uint32_t>(outputs.size())};

    // 逐个实例构造 Tensor，用于表达 tensor list 内每个实例独立的 shape/dtype
    std::vector<uint32_t> inputInstanceNum;
    std::vector<std::unique_ptr<gert::Tensor>> tensorHolder;
    std::vector<gert::Tensor*> inputTensors;
    for (const auto& list : inputs) {
        inputInstanceNum.push_back(static_cast<uint32_t>(list.size()));
        for (const auto& spec : list) {
            tensorHolder.emplace_back(std::make_unique<gert::Tensor>(
                spec.first, gert::StorageFormat(ge::FORMAT_ND, ge::FORMAT_ND, gert::ExpandDimsType()),
                gert::TensorPlacement::kOnHost, spec.second, nullptr));
            inputTensors.push_back(tensorHolder.back().get());
        }
    }

    std::vector<gert::StorageShape> outputShapes;
    std::vector<gert::StorageShape*> outputShapePtrs;
    outputShapes.reserve(outputs.size());
    for (const auto& spec : outputs) {
        outputShapes.push_back(spec.first);
    }
    for (auto& shape : outputShapes) {
        outputShapePtrs.push_back(&shape);
    }

    auto tilingData = gert::TilingData::CreateCap(4096);
    auto workspace = gert::ContinuousVector::Create<size_t>(4096);
    gert::TilingContextFaker faker;
    faker.SetOpType(std::string(kOpType))
        .NodeIoNum(inputs.size(), outputs.size())
        .IrInstanceNum(inputInstanceNum, outInstanceNum)
        .InputTensors(inputTensors)
        .OutputShapes(outputShapePtrs)
        .CompileInfo(&compileInfo_)
        .PlatformInfo(reinterpret_cast<char*>(&platformInfo_))
        .TilingData(tilingData.get())
        .Workspace(reinterpret_cast<gert::ContinuousVector*>(workspace.get()));
    for (size_t i = 0; i < outputs.size(); ++i) {
        faker.NodeOutputTd(static_cast<int32_t>(i), outputs[i].second, ge::FORMAT_ND, ge::FORMAT_ND);
    }
    auto contextHolder = faker.Build();

    gert::TilingContext* tilingContext = contextHolder.GetContext<gert::TilingContext>();
    if (tilingContext == nullptr) {
        return result;
    }
    // 平台信息已在 Init() 中填充到 platformInfo_（该指针随上下文传入），tiling 侧经 compileInfo 取核数/UB，
    // 多实例场景下不再通过 GetPlatformInfo() 回写，避免命中 context 中非实例展开的槽位。

    // 每个用例独立 ErrorManager 上下文；失败后快照首错，再二次读取确认无重复上报。
    ScopedErrorContext errorContext;
    result.status = opImpl->tiling(tilingContext);
    result.error = CaptureError();
    result.duplicateCount = CaptureError().count;
    result.tilingKey = tilingContext->GetTilingKey();
    return result;
}

