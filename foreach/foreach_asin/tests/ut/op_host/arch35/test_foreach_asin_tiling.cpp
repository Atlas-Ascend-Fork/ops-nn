static void DoListCase(const std::vector<gert::StorageShape>& xShapes, ge::DataType dt, uint64_t expectKey,
                       uint32_t expectBlockDim, int64_t expectPerCore, int32_t expectNeedCore, int64_t expectLastCore)
{
    struct ForeachAsinCompileInfo {
        int64_t coreNum;
        int64_t ubSize;
    } ci = {64, 253952};
    std::vector<gert::TilingContextPara::TensorDescription> tensors;
    for (const auto& shape : xShapes) {
        tensors.emplace_back(shape, dt, ge::FORMAT_ND);
    }
    const uint32_t instanceNum = static_cast<uint32_t>(tensors.size());
    gert::TilingContextPara tilingContextPara("ForeachAsin", tensors, tensors, {instanceNum}, {instanceNum}, &ci, 64,
                                              253952, 4096);
    TilingInfo info;
    ASSERT_TRUE(ExecuteTiling(tilingContextPara, info));
    EXPECT_EQ(info.tilingKey, expectKey);
    EXPECT_EQ(info.blockNum, expectBlockDim);
    ASSERT_EQ(info.workspaceSizes.size(), 1U);
    EXPECT_EQ(info.workspaceSizes[0], 16777216U);
    ASSERT_GE(info.tilingDataSize, sizeof(ForeachAsinTilingData));
    const auto* tilingData = reinterpret_cast<const ForeachAsinTilingData*>(info.tilingData.get());
    EXPECT_EQ(tilingData->tensorNum, static_cast<int32_t>(xShapes.size()));
    EXPECT_EQ(tilingData->perCoreElements, expectPerCore);
    EXPECT_EQ(tilingData->needCoreNum, expectNeedCore);
    EXPECT_EQ(tilingData->lastCoreElements, expectLastCore);
    EXPECT_EQ(tilingData->tensorCumulativeOffset[0], 0);
    for (size_t i = 0; i < xShapes.size(); ++i) {
        EXPECT_EQ(tilingData->tensorCumulativeOffset[i + 1] - tilingData->tensorCumulativeOffset[i],
                  xShapes[i].GetStorageShape().GetShapeSize());
    }
}

