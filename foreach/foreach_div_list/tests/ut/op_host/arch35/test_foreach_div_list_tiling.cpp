// 外层包装改为 OP_LOGE_WITHOUT_REPORT 后，一次故障只应落一条首错且二次读取为空。
TEST_F(foreach_div_list_arch35_tiling_test, foreach_div_list_arch35_first_error_unique)
{
    TilingRunner runner;
    ASSERT_TRUE(runner.Init());
    auto inputs = DefaultInputs(2);
    inputs[1][1] = MakeSpec({4}, ge::DT_FLOAT);
    auto result = runner.Run(inputs, DefaultOutputs(2));
    EXPECT_EQ(result.status, ge::GRAPH_FAILED);
    // 内层漏报会得到 0 条，外层重复首报会得到 2 条，二者都必须判定失败
    ASSERT_EQ(result.error.count, 1U) << "exactly one ErrorManager first error expected";
    EXPECT_EQ(result.error.code, "EZ0009");
    EXPECT_EQ(ErrorValue(result.error, "param_name"), "x2");
    EXPECT_EQ(result.duplicateCount, 0U) << "duplicate report detected";
}
